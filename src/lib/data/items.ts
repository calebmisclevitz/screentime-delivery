const INR_PER_USD = 80;

/** Preserve the seeded listings' approximate value in local currency. */
export const ITEMS: Item[] = SEEDED_ITEMS.map((item) => ({
  ...item,
  price: item.price * INR_PER_USD,
}));

export const ME: Seller = {
  id: "me",
  name: "You",
  rating: 4.9,
  sales: 12,
};

/** Seeded listings attributed to the demo user, kept out of the buy-side feed. */
const MY_LISTING_IDS: Record<string, "active" | "sold"> = {
  "braun-alarm-clock": "active",
  "mustard-studio-mug": "active",
  "lime-watering-can": "sold",
  "silver-spiral-pendant": "sold",
};

export const MY_SEEDED_LISTINGS: Item[] = ITEMS.filter(
  (item) => item.id in MY_LISTING_IDS,
).map((item) => ({
  ...item,
  seller: ME,
  status: MY_LISTING_IDS[item.id],
}));

/** Everything a buyer can browse — the demo user's own listings are excluded. */
export const MARKET_ITEMS: Item[] = ITEMS.filter(
  (item) => !(item.id in MY_LISTING_IDS),
);

/** Images offered in the listing form's photo picker. */
export const STOCK_IMAGES = ITEMS.map((item) => item.images[0]);

const FALLBACK_BACKGROUND = "#f1feba";

/** Color behind a stock cutout, used when a seller picks a library photo. */
export function backgroundForImage(src: string): string {
  return (
    ITEMS.find((item) => item.images.includes(src))?.backgroundColor ??
    FALLBACK_BACKGROUND
  );
}
